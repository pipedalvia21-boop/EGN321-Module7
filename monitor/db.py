"""SQLite storage for the monitor.

The database is a superset of the Module 6 history database:
  * `datasets` and `sensor_readings` keep the Module 6 columns and constraints
    (raw value, accepted value only when status = OK, status, reason, timestamp source).
    Module 6 rows are imported unchanged.
  * `sensor_readings.source_ref` says which source row a live reading replays.
  * timestamp_source gains one value, 'received': the time the monitor received the reading.
  * New tables: `events` (what happened), `kv` (heartbeats, replay cursor, health),
    `alert_state` (survives restarts).

Generated by `python init_db.py` (or automatically on first start) from data/module6_sensor_history.db.
"""
import json
import logging
import sqlite3
from datetime import datetime
from pathlib import Path

from monitor.history_m6 import TS_FORMAT, parse_ts  # noqa: F401  (re-exported)

SCHEMA_VERSION = 2
TS_SOURCES = "('original', 'reconstructed', 'received')"
STATUSES = "('OK', 'OUT_OF_RANGE', 'MISSING', 'SUSPICIOUS', 'FAULT')"

SCHEMA = f"""
CREATE TABLE IF NOT EXISTS schema_info (version INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS datasets (
    name              TEXT PRIMARY KEY,
    description       TEXT NOT NULL,
    source_file       TEXT NOT NULL,
    interval_seconds  REAL NOT NULL CHECK (interval_seconds > 0),
    timestamp_source  TEXT NOT NULL CHECK (timestamp_source IN {TS_SOURCES}),
    timestamp_note    TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sensor_readings (
    id               INTEGER PRIMARY KEY AUTOINCREMENT,
    dataset          TEXT    NOT NULL REFERENCES datasets(name),
    sample_number    INTEGER NOT NULL,
    timestamp        TEXT    NOT NULL,
    timestamp_source TEXT    NOT NULL CHECK (timestamp_source IN {TS_SOURCES}),
    sensor_name      TEXT    NOT NULL,
    unit             TEXT    NOT NULL,
    raw_value        REAL,
    accepted_value   REAL,
    status           TEXT    NOT NULL CHECK (status IN {STATUSES}),
    source_status    TEXT,
    status_reason    TEXT,
    source_ref       TEXT,
    UNIQUE (dataset, sensor_name, sample_number),
    CHECK (accepted_value IS NULL OR status = 'OK'),
    CHECK (accepted_value IS NULL OR accepted_value = raw_value)
);
CREATE INDEX IF NOT EXISTS idx_dataset_sensor_time ON sensor_readings(dataset, sensor_name, timestamp);
CREATE TABLE IF NOT EXISTS events (
    id       INTEGER PRIMARY KEY AUTOINCREMENT,
    ts       TEXT NOT NULL,
    level    TEXT NOT NULL,
    source   TEXT NOT NULL,
    event    TEXT NOT NULL,
    message  TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_events_ts ON events(ts);
CREATE TABLE IF NOT EXISTS kv (
    key        TEXT PRIMARY KEY,
    value      TEXT,
    updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS alert_state (
    name        TEXT PRIMARY KEY,
    active      INTEGER NOT NULL CHECK (active IN (0, 1)),
    since       TEXT,
    last_median REAL,
    updated_at  TEXT NOT NULL
);
"""

READING_COLUMNS = ["dataset", "sample_number", "timestamp", "timestamp_source", "sensor_name", "unit",
                   "raw_value", "accepted_value", "status", "source_status", "status_reason", "source_ref"]
M6_COLUMNS = READING_COLUMNS[:-1]

log = logging.getLogger("db")


def fmt_ts(dt: datetime) -> str:
    return dt.strftime(TS_FORMAT)[:-3]


def ts_from_epoch(seconds: float) -> str:
    return fmt_ts(datetime.fromtimestamp(seconds))


def epoch(ts: str) -> float:
    return parse_ts(ts).timestamp()


def connect(path) -> sqlite3.Connection:
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(path), timeout=10, isolation_level=None)   # autocommit
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")      # dashboard reads while the collector writes
    conn.execute("PRAGMA busy_timeout=10000")
    conn.execute("PRAGMA foreign_keys=ON")
    return conn


def init_db(settings, reset=False) -> dict:
    """Create the schema and import the Module 6 history once. Safe to call on every start."""
    db_path = Path(settings.db_path)
    if reset:
        for suffix in ("", "-wal", "-shm"):
            Path(str(db_path) + suffix).unlink(missing_ok=True)
    conn = connect(db_path)
    conn.executescript(SCHEMA)
    if conn.execute("SELECT COUNT(*) FROM schema_info").fetchone()[0] == 0:
        conn.execute("INSERT INTO schema_info VALUES (?)", (SCHEMA_VERSION,))

    imported = 0
    if conn.execute("SELECT COUNT(*) FROM sensor_readings WHERE dataset != ?",
                    (settings.live_dataset,)).fetchone()[0] == 0:
        if not Path(settings.module6_db).exists():
            raise FileNotFoundError(f"Module 6 history database not found: {settings.module6_db}")
        conn.execute("ATTACH DATABASE ? AS m6", (str(settings.module6_db),))
        conn.execute("BEGIN")
        conn.execute("INSERT INTO datasets SELECT * FROM m6.datasets")
        cols = ", ".join(M6_COLUMNS)
        imported = conn.execute(
            f"INSERT INTO sensor_readings ({cols}) SELECT {cols} FROM m6.sensor_readings ORDER BY id").rowcount
        conn.execute("COMMIT")
        conn.execute("DETACH DATABASE m6")

    register_live_dataset(conn, settings)
    summary = {"imported_module6_rows": imported,
               "total_rows": conn.execute("SELECT COUNT(*) FROM sensor_readings").fetchone()[0]}
    conn.close()
    return summary


def register_live_dataset(conn, settings, update=False):
    """Create the live dataset row. Only the collector passes update=True: it owns the interval,
    so a dashboard started with different settings can never change how live gaps are judged."""
    conflict = ("DO UPDATE SET interval_seconds = excluded.interval_seconds, description = excluded.description, "
                "timestamp_note = excluded.timestamp_note") if update else "DO NOTHING"
    conn.execute(
        "INSERT INTO datasets VALUES (?, ?, ?, ?, 'received', ?) "
        f"ON CONFLICT(name) {conflict}",
        (settings.live_dataset,
         f"Live collector: replays Module 6 '{settings.source_dataset}/{settings.source_sensor}' "
         f"at {settings.replay_speed:g}x speed",
         f"sensor_readings (dataset '{settings.source_dataset}')", settings.interval_s,
         "Timestamp = local time the collector received and stored the reading. "
         "source_ref names the replayed Module 6 row and its original timestamp."))


# ---------------------------------------------------------------- readings
def insert_reading(conn, rec: dict) -> int:
    cols = ", ".join(READING_COLUMNS)
    cur = conn.execute(f"INSERT INTO sensor_readings ({cols}) VALUES ({', '.join('?' * len(READING_COLUMNS))})",
                       tuple(rec.get(c) for c in READING_COLUMNS))
    return cur.lastrowid


def next_sample_number(conn, dataset, sensor) -> int:
    n = conn.execute("SELECT MAX(sample_number) FROM sensor_readings WHERE dataset = ? AND sensor_name = ?",
                     (dataset, sensor)).fetchone()[0]
    return 1 if n is None else n + 1


def recent_readings(conn, dataset, sensor, limit=30):
    rows = conn.execute("SELECT * FROM sensor_readings WHERE dataset = ? AND sensor_name = ? "
                        "ORDER BY timestamp DESC, id DESC LIMIT ?", (dataset, sensor, limit)).fetchall()
    return [dict(r) for r in reversed(rows)]


def readings_since(conn, dataset, sensor, since_ts: str):
    return [dict(r) for r in conn.execute(
        "SELECT * FROM sensor_readings WHERE dataset = ? AND sensor_name = ? AND timestamp > ? "
        "ORDER BY timestamp, id", (dataset, sensor, since_ts))]


def last_accepted(conn, dataset, sensor):
    row = conn.execute("SELECT * FROM sensor_readings WHERE dataset = ? AND sensor_name = ? "
                       "AND accepted_value IS NOT NULL ORDER BY timestamp DESC, id DESC LIMIT 1",
                       (dataset, sensor)).fetchone()
    return dict(row) if row else None


# ---------------------------------------------------------------- events, kv, alert state
def record_event(conn, level: str, source: str, event: str, message: str, ts: str = None, logger=None):
    """Store an event in SQLite and write the same line to the process log."""
    ts = ts or fmt_ts(datetime.now())
    (logger or log).log(getattr(logging, level), "%s %s", event, message)
    try:
        conn.execute("INSERT INTO events (ts, level, source, event, message) VALUES (?, ?, ?, ?, ?)",
                     (ts, level, source, event, message))
    except sqlite3.Error as exc:   # the log line above is still written
        (logger or log).error("APPLICATION_ERROR could not store event %s: %s", event, exc)


def recent_events(conn, limit=20):
    return [dict(r) for r in conn.execute("SELECT * FROM events ORDER BY id DESC LIMIT ?", (limit,))]


def kv_get(conn, key, default=None):
    row = conn.execute("SELECT value FROM kv WHERE key = ?", (key,)).fetchone()
    return default if row is None else row[0]


def kv_get_json(conn, key, default=None):
    value = kv_get(conn, key)
    return default if value is None else json.loads(value)


def kv_set(conn, key, value, ts: str = None):
    if not isinstance(value, str):
        value = json.dumps(value)
    conn.execute("INSERT INTO kv VALUES (?, ?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value, "
                 "updated_at = excluded.updated_at", (key, value, ts or fmt_ts(datetime.now())))


def load_alert_state(conn, name):
    row = conn.execute("SELECT * FROM alert_state WHERE name = ?", (name,)).fetchone()
    return dict(row) if row else None


def save_alert_state(conn, name, active, since, last_median, ts):
    conn.execute("INSERT INTO alert_state VALUES (?, ?, ?, ?, ?) ON CONFLICT(name) DO UPDATE SET "
                 "active = excluded.active, since = excluded.since, last_median = excluded.last_median, "
                 "updated_at = excluded.updated_at", (name, int(active), since, last_median, ts))
